package deployexport

import (
	"fmt"
	"strings"
)

const header = "# Generated by Nexmesh from the workspace canvas. Review it before use; it is a starting point, not a hardened production image.\n"

// majorOf returns "22" for "22.11.0".
func majorOf(v, fallback string) string {
	v = strings.TrimPrefix(strings.TrimSpace(v), "v")
	if v == "" {
		return fallback
	}
	return strings.SplitN(v, ".", 2)[0]
}

func minorOf(v, fallback string) string {
	v = strings.TrimPrefix(strings.TrimSpace(v), "v")
	parts := strings.Split(v, ".")
	if len(parts) < 2 {
		return fallback
	}
	return parts[0] + "." + parts[1]
}

// dockerfile renders a Dockerfile for a detected project.
func dockerfile(catalogID string, p *Project, versions map[string]string, port int) string {
	var b strings.Builder
	b.WriteString(header)
	switch catalogID {
	case "nestjs", "nodejs":
		node := majorOf(versions["nodejs"], "22")
		install := nodeInstall(p, false)
		fmt.Fprintf(&b, "FROM node:%s-alpine AS build\nWORKDIR /app\nCOPY package*.json pnpm-lock.yaml* yarn.lock* ./\nRUN %s\nCOPY . .\n", node, install)
		if p.Script["build"] != "" {
			fmt.Fprintf(&b, "RUN %s run build\n", runner(p))
		}
		fmt.Fprintf(&b, "\nFROM node:%s-alpine\nWORKDIR /app\nENV NODE_ENV=production\nCOPY --from=build /app /app\nRUN %s\n", node, pruneCmd(p))
		if port > 0 {
			fmt.Fprintf(&b, "EXPOSE %d\n", port)
		}
		fmt.Fprintf(&b, "CMD %s\n", nodeCmd(catalogID, p))
	case "react", "angular":
		node := majorOf(versions["nodejs"], "22")
		out := "dist"
		if catalogID == "react" && p.Deps["react-scripts"] {
			out = "build"
		}
		fmt.Fprintf(&b, "FROM node:%s-alpine AS build\nWORKDIR /app\nCOPY package*.json pnpm-lock.yaml* yarn.lock* ./\nRUN %s\nCOPY . .\nRUN %s run build\n", node, nodeInstall(p, false), runner(p))
		fmt.Fprintf(&b, "\n# The build output folder is %q; change it here if your project builds elsewhere.\nFROM nginx:alpine\nCOPY --from=build /app/%s /usr/share/nginx/html\nEXPOSE 80\n", out, out)
	case "htmlcss":
		b.WriteString("FROM nginx:alpine\nCOPY . /usr/share/nginx/html\nEXPOSE 80\n")
	case "fastapi", "python":
		py := minorOf(versions["python"], "3.12")
		fmt.Fprintf(&b, "FROM python:%s-slim\nWORKDIR /app\nENV PYTHONUNBUFFERED=1\n", py)
		if p.Files["requirements.txt"] {
			b.WriteString("COPY requirements.txt ./\nRUN pip install --no-cache-dir -r requirements.txt\nCOPY . .\n")
		} else {
			b.WriteString("COPY . .\nRUN pip install --no-cache-dir .\n")
		}
		if catalogID == "fastapi" {
			if port == 0 {
				port = 8000
			}
			fmt.Fprintf(&b, "EXPOSE %d\nCMD [\"uvicorn\", %q, \"--host\", \"0.0.0.0\", \"--port\", \"%d\"]\n", port, p.Module, port)
		} else {
			b.WriteString("# Set the command that starts your program.\nCMD [\"python\", \"main.py\"]\n")
		}
	case "go":
		goV := minorOf(versions["go"], "1.23")
		fmt.Fprintf(&b, "FROM golang:%s AS build\nWORKDIR /src\nCOPY go.mod go.sum* ./\nRUN go mod download\nCOPY . .\nRUN CGO_ENABLED=0 go build -o /out/app .\n\nFROM gcr.io/distroless/static-debian12\nCOPY --from=build /out/app /app\n", goV)
		if port > 0 {
			fmt.Fprintf(&b, "EXPOSE %d\n", port)
		}
		b.WriteString("ENTRYPOINT [\"/app\"]\n")
	}
	return b.String()
}

func nodeInstall(p *Project, prod bool) string {
	switch p.PM {
	case "pnpm":
		return "corepack enable && pnpm install --frozen-lockfile"
	case "yarn":
		return "corepack enable && yarn install --frozen-lockfile"
	}
	if p.Files["package-lock.json"] {
		return "npm ci"
	}
	return "npm install"
}

func pruneCmd(p *Project) string {
	switch p.PM {
	case "pnpm":
		return "corepack enable && pnpm prune --prod"
	case "yarn":
		return "true"
	}
	return "npm prune --omit=dev"
}

func runner(p *Project) string {
	switch p.PM {
	case "pnpm":
		return "pnpm"
	case "yarn":
		return "yarn"
	}
	return "npm"
}

func nodeCmd(catalogID string, p *Project) string {
	if catalogID == "nestjs" {
		return `["node", "dist/main.js"]`
	}
	if p.Script["start"] != "" {
		return fmt.Sprintf(`["%s", "start"]`, runner(p))
	}
	if p.Main != "" {
		return fmt.Sprintf(`["node", %q]`, p.Main)
	}
	return `["node", "index.js"]`
}

