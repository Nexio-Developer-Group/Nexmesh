func mermaidID(i int) string { return fmt.Sprintf("n%d", i+1) }

func esc(s string) string {
	return strings.NewReplacer(`"`, "'", "\n", " ", "<", "(", ">", ")", "|", "/").Replace(s)
}

func label(n Node) string {
	parts := []string{n.Name}
	if n.Version != "" {
		parts = append(parts, n.Version)
	}
	if n.Mode != "" {
		parts = append(parts, n.Mode)
	}
	if n.Environment != "" {
		parts = append(parts, n.Environment)
	}
	return strings.Join(parts, " · ")
}

// Mermaid renders the view as a Mermaid flowchart.
func Mermaid(v *View) string {
	var b strings.Builder
	b.WriteString("flowchart LR\n")
	ids := map[string]string{}
	for i, n := range v.Nodes {
		ids[n.ID] = mermaidID(i)
	}
	for _, l := range v.Layers {
		var in []Node
		for _, n := range v.Nodes {
			if n.Layer == l.ID {
				in = append(in, n)
			}
		}
		if len(in) == 0 {
			continue
		}
		fmt.Fprintf(&b, "  subgraph %s[\"%s\"]\n", l.ID, l.Label)
		for _, n := range in {
			fmt.Fprintf(&b, "    %s[\"%s\"]\n", ids[n.ID], esc(label(n)))
		}
		b.WriteString("  end\n")
	}
	for _, e := range v.Edges {
		arrow := "-->"
		if e.State == "unreachable" {
			arrow = "-.->"
		}
		fmt.Fprintf(&b, "  %s %s|\"%s · %s\"| %s\n", ids[e.From], arrow, esc(e.Name), e.State, ids[e.To])
	}
	b.WriteString("  classDef highlight stroke:#1676fe,stroke-width:3px\n  classDef bad stroke:#e5484d,stroke-width:2px\n")
	for _, n := range v.Nodes {
		switch {
		case n.Highlight:
			fmt.Fprintf(&b, "  class %s highlight\n", ids[n.ID])
		case n.State == "failed" || n.State == "test_failed":
			fmt.Fprintf(&b, "  class %s bad\n", ids[n.ID])
		}
	}
	return b.String()
}

// Markdown renders a summary suitable for committing to a repository.
func Markdown(v *View) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Architecture: %s\n\nGenerated by Nexmesh from the workspace canvas. It contains no secret values.\n\n", v.Workspace)
	b.WriteString("```mermaid\n" + Mermaid(v) + "```\n\n")
	b.WriteString("## Components\n\n")
	for _, l := range v.Layers {
		var in []Node
		for _, n := range v.Nodes {
			if n.Layer == l.ID {
				in = append(in, n)
			}
		}
		if len(in) == 0 {
			continue
		}
		fmt.Fprintf(&b, "### %s\n\n| Component | Version | Mode | State |\n| :-- | :-- | :-- | :-- |\n", l.Label)
		for _, n := range in {
			fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", esc(n.Name), n.Version, n.Mode, strings.ReplaceAll(n.State, "_", " "))
		}
		b.WriteString("\n")
	}
	if len(v.Edges) > 0 {
		names := map[string]string{}
		for _, n := range v.Nodes {
			names[n.ID] = n.Name
		}
		b.WriteString("## Connections\n\n| From | To | Name | State | Variables |\n| :-- | :-- | :-- | :-- | :-- |\n")
		for _, e := range v.Edges {
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %d |\n", esc(names[e.From]), esc(names[e.To]), e.Name, e.State, e.Variables)
		}
		b.WriteString("\n")
	}
	if len(v.Drift) > 0 {
		b.WriteString("## Needs attention\n\n")
		for _, d := range v.Drift {
			fmt.Fprintf(&b, "- **%s**: %s\n", d.Kind, esc(d.Message))
		}
	}
	return b.String()
}

var stateColor = map[string]string{
	"healthy": "#2fbf71", "running": "#2fbf71", "ready": "#2fbf71", "connected": "#2fbf71",
	"degraded": "#e0a526", "unreachable": "#e5484d", "failed": "#e5484d", "test_failed": "#e5484d",
}

// SVG renders a standalone image: one row per layer, cards as boxes, lines as
// arrows. States are written out as words as well as coloured.
func SVG(v *View) string {
	const cardW, cardH, gapX, gapY, padX, rowLabel = 200, 64, 28, 54, 24, 120
	type pos struct{ x, y int }
	where := map[string]pos{}
	y := 24
	var rows []struct {
		l  Layer
		ns []Node
		y  int
	}
	maxCols := 1
	for _, l := range v.Layers {
		var in []Node
		for _, n := range v.Nodes {
			if n.Layer == l.ID {
				in = append(in, n)
			}
		}
		if len(in) == 0 {
			continue
		}
		rows = append(rows, struct {
			l  Layer
			ns []Node
			y  int
		}{l, in, y})
		for i, n := range in {
			where[n.ID] = pos{padX + rowLabel + i*(cardW+gapX), y}
		}
		if len(in) > maxCols {
			maxCols = len(in)
		}
		y += cardH + gapY
	}
	w := padX*2 + rowLabel + maxCols*(cardW+gapX)
	h := y + 8
	if len(rows) == 0 {
		w, h = 360, 80
	}
	var b strings.Builder
	fmt.Fprintf(&b, `<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d" role="img" aria-label="Architecture of %s" font-family="Plus Jakarta Sans, Arial, sans-serif">`, w, h, w, h, html.EscapeString(v.Workspace))
	b.WriteString(`<defs><marker id="a" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0 0L10 5L0 10z" fill="#7a86a8"/></marker></defs>`)
	fmt.Fprintf(&b, `<rect width="%d" height="%d" fill="#0b1530"/>`, w, h)
	if len(rows) == 0 {
		b.WriteString(`<text x="24" y="46" fill="#c9d3ee" font-size="14">No components on the canvas yet.</text></svg>`)
		return b.String()
	}
	for _, r := range rows {
		fmt.Fprintf(&b, `<text x="%d" y="%d" fill="#7a86a8" font-size="12" font-weight="700">%s</text>`, padX, r.y+cardH/2+4, html.EscapeString(strings.ToUpper(r.l.Label)))
	}
	// Lines first so cards sit on top.
	edges := append([]Edge(nil), v.Edges...)
	sort.SliceStable(edges, func(i, j int) bool { return edges[i].ID < edges[j].ID })
	for _, e := range edges {
		a, c := where[e.From], where[e.To]
		x1, y1, x2, y2 := a.x+cardW/2, a.y+cardH, c.x+cardW/2, c.y
		if a.y == c.y { // same layer: side to side
			x1, y1, x2, y2 = a.x+cardW, a.y+cardH/2, c.x, c.y+cardH/2
			if c.x < a.x {
				x1, x2 = a.x, c.x+cardW
			}
		} else if c.y < a.y {
			y1, y2 = a.y, c.y+cardH
		}
		col := stateColor[e.State]
		if col == "" {
			col = "#7a86a8"
		}
		dash := ""
		if e.State == "unreachable" {
			dash = ` stroke-dasharray="3 5"`
		} else if e.State == "pending" || e.State == "degraded" {
			dash = ` stroke-dasharray="6 4"`
		}
		sw := 2
		if e.Highlight {
			sw = 4
		}
		fmt.Fprintf(&b, `<path d="M%d %dC%d %d %d %d %d %d" fill="none" stroke="%s" stroke-width="%d"%s marker-end="url(#a)"/>`, x1, y1, x1, (y1+y2)/2, x2, (y1+y2)/2, x2, y2, col, sw, dash)
		fmt.Fprintf(&b, `<text x="%d" y="%d" fill="#c9d3ee" font-size="10" text-anchor="middle">%s · %s</text>`, (x1+x2)/2, (y1+y2)/2-4, html.EscapeString(e.Name), e.State)
	}
	for _, n := range v.Nodes {
		p, ok := where[n.ID]
		if !ok {
			continue
		}
		stroke, sw := "#2a3a66", 1
		if n.Highlight {
			stroke, sw = "#1676fe", 3
		} else if c := stateColor[n.State]; c == "#e5484d" {
			stroke = c
		}
		fmt.Fprintf(&b, `<rect x="%d" y="%d" width="%d" height="%d" rx="12" fill="#0e1730" stroke="%s" stroke-width="%d"/>`, p.x, p.y, cardW, cardH, stroke, sw)
		fmt.Fprintf(&b, `<text x="%d" y="%d" fill="#fff" font-size="14" font-weight="700">%s</text>`, p.x+12, p.y+24, html.EscapeString(trunc(n.Name, 24)))
		sub := strings.TrimSpace(strings.Join([]string{n.Version, n.Mode}, " · "))
		fmt.Fprintf(&b, `<text x="%d" y="%d" fill="#7a86a8" font-size="11">%s</text>`, p.x+12, p.y+42, html.EscapeString(sub))
		fmt.Fprintf(&b, `<text x="%d" y="%d" fill="%s" font-size="11" font-weight="700">%s</text>`, p.x+12, p.y+57, orGrey(stateColor[n.State]), html.EscapeString(strings.ReplaceAll(n.State, "_", " ")))
	}
	b.WriteString(`</svg>`)
	return b.String()
}

func orGrey(c string) string {
	if c == "" {
		return "#7a86a8"
	}
	return c
}

func trunc(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	return string(r[:n-1]) + "…"
}
